"""Copy content.json into index.html: the embedded data block, the SEO/link-preview tags in <head>,
and the plain-text fallback for visitors and crawlers without JavaScript.
Edit text ONLY in content.json, then run:   python tools/sync_content.py
Check without writing (used by lint/CI):    python tools/sync_content.py --check"""
import json,re,sys,pathlib,html
root=pathlib.Path(__file__).resolve().parent.parent
c=json.loads((root/'content.json').read_text(encoding='utf-8'))
H=(root/'index.html').read_text(encoding='utf-8')
S=c['settings'];hero=c['hero'];E=html.escape
URL=S.get('site_url','https://abdullahsulehri.github.io/interactive-cv/')
plain=lambda s:re.sub(r'\*([^*]+)\*',r'\1',s).replace('\n',' ')
name=' '.join(hero['name'])
person={'@context':'https://schema.org','@type':'Person','name':name,'jobTitle':hero['role_line'].split(' · ')[0],'url':URL,
 'email':'mailto:'+S['email'],'telephone':S['phone'].replace(' ',''),'sameAs':[S['linkedin']],
 'address':{'@type':'PostalAddress','addressLocality':hero.get('city','Lahore'),'addressCountry':'PK'},'knowsLanguage':['English','Urdu'],'image':URL+'assets/portrait.webp'}
seo=f'''<!--seo:start (generated by tools/sync_content.py: edit content.json, not this block)-->
<title>{E(S['site_title'])}</title>
<meta name="description" content="{E(S['meta_description'])}">
<link rel="canonical" href="{URL}">
<meta property="og:type" content="profile">
<meta property="og:url" content="{URL}">
<meta property="og:title" content="{E(S['site_title'])}">
<meta property="og:description" content="{E(plain(hero['thesis']))}">
<meta property="og:image" content="{URL}assets/og-image.jpg">
<meta property="og:image:width" content="1200">
<meta property="og:image:height" content="630">
<meta name="twitter:card" content="summary_large_image">
<meta name="twitter:title" content="{E(S['site_title'])}">
<meta name="twitter:description" content="{E(plain(hero['thesis']))}">
<meta name="twitter:image" content="{URL}assets/og-image.jpg">
<link rel="preload" as="image" href="{E(hero.get('portrait','assets/portrait.webp'))}" fetchpriority="high">
<script type="application/ld+json">{json.dumps(person,ensure_ascii=False)}</script>
<!--seo:end-->'''
roles=''.join(f"<li><b>{E(x['title'])}</b>, {E(x['company'])} ({E(x['dates'])}): {E(x.get('headline',''))}</li>" for x in reversed(c['experience']['items']))
nos=f'''<!--noscript:start (generated by tools/sync_content.py)-->
<noscript><div class="nojs">
<h1>{E(name)}</h1><p><b>{E(hero['role_line'])}</b></p><p>{E(plain(hero['thesis']))}</p>
<h2>Experience</h2><ul>{roles}</ul>
<h2>Contact</h2><p><a href="mailto:{E(S['email'])}">{E(S['email'])}</a> · {E(S['phone'])} · <a href="{E(S['linkedin'])}">LinkedIn</a> · <a href="cv/Abdullah-Sulehri-CV.pdf">Download CV (PDF)</a></p>
<p>This site is interactive; turn on JavaScript for the full version.</p>
</div></noscript>
<!--noscript:end-->'''
emb=json.dumps(c,ensure_ascii=False).replace('</','<\\/')
def put(h):
    h=re.sub(r'(<script id="content-data" type="application/json">)(.*?)(</script>)',lambda m:m.group(1)+emb+m.group(3),h,count=1,flags=re.S)
    if '<!--seo:start' in h: h=re.sub(r'<!--seo:start.*?<!--seo:end-->',lambda m:seo,h,count=1,flags=re.S)
    else:
        h=re.sub(r'<title>.*?</title>\n(?:<meta (?:name="description"|property="og:[a-z]+")[^>]*>\n)*',lambda m:seo+'\n',h,count=1,flags=re.S)
    if '<!--noscript:start' in h: h=re.sub(r'<!--noscript:start.*?<!--noscript:end-->',lambda m:nos,h,count=1,flags=re.S)
    else: h=re.sub(r'(<body[^>]*>)',lambda m:m.group(1)+'\n'+nos,h,count=1)
    return h
new=put(H)
if '--check' in sys.argv:
    ok=new==H;print('content in sync' if ok else 'OUT OF SYNC: run python tools/sync_content.py');sys.exit(0 if ok else 1)
(root/'index.html').write_text(new,encoding='utf-8')
(root/'content.json').write_text(json.dumps(c,ensure_ascii=False,indent=1),encoding='utf-8')
print('index.html updated from content.json')
